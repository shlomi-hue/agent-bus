import { build } from "esbuild";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outfile = join(root, "dist", "chat", "app.js");
const embedded = join(root, "src", "generated", "chat-app.ts");
const assets = join(root, "src", "generated", "chat-assets.ts");

await mkdir(dirname(outfile), { recursive: true });

try {
  await build({
    entryPoints: [join(root, "src", "chat", "client.ts")],
    bundle: true,
    format: "iife",
    platform: "browser",
    target: "es2022",
    outfile,
    minify: true,
    legalComments: "none",
    logLevel: "warning",
  });
} catch (error) {
  console.error("Chat client bundle failed.");
  console.error(error);
  process.exit(1);
}

const code = await readFile(outfile, "utf8");
if (code.length < 1000 || !code.includes("ab-seen:")) {
  console.error("Chat client bundle is empty or is not the chat client.");
  process.exit(1);
}

const css = [
  await readFile(join(root, "src", "http", "styles", "tokens.css"), "utf8"),
  await readFile(join(root, "src", "http", "styles", "components.css"), "utf8"),
  await readFile(join(root, "src", "http", "styles", "app.css"), "utf8"),
].join("\n");
const inter = await readFile(join(root, "src", "http", "fonts", "inter.woff2"));
const jetbrains = await readFile(join(root, "src", "http", "fonts", "jetbrains-mono.woff2"));

await mkdir(dirname(embedded), { recursive: true });
await writeFile(
  embedded,
  "// Generated by scripts/build-chat.ts. Do not edit.\n" +
    `export const chatAppSource = ${JSON.stringify(code)};\n`,
);
await writeFile(
  assets,
  "// Generated by scripts/build-chat.ts. Do not edit.\n" +
    `export const chatCss = ${JSON.stringify(css)};\n` +
    `export const fontInter = ${JSON.stringify(inter.toString("base64"))};\n` +
    `export const fontJetbrains = ${JSON.stringify(jetbrains.toString("base64"))};\n`,
);

console.log(`Wrote ${outfile} (${code.length} bytes)`);
